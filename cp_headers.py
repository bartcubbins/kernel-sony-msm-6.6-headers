#!/usr/bin/env python3
# Generates kernel UAPI headers for this kernel version and the matching
# Android.bp modules.
#
# - kernel-headers/: headers of the kernel itself (UAPI + ARCH UAPI),
# without the ones bionic already ships
# - techpack-headers/<name>/: headers of each techpack
# - Android.bp: cc_library_headers modules for all of the above
#
# Each header goes through the kernel's headers_install.sh and the result
# is reported as new / updated / unchanged compared to the previous run.
# The log is written to out/kernel-X.Y/cp_headers.log.
#
# Usage: python3 cp_headers.py [-v]

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent  # kernel/sony/msm-X.Y/common-headers
KERNEL_PATH = HERE.parent
KERNEL = KERNEL_PATH / "kernel"
SRC = KERNEL / "include"

VERSION = KERNEL_PATH.name.split("-", 1)[1]  # e.g. "6.6"
AOSP_ROOT = HERE.parents[3]
LOG_PATH = AOSP_ROOT / "out" / f"kernel-{VERSION}" / "cp_headers.log"

CORE_DIR = HERE / "kernel-headers"
TECHPACKS_DIR = HERE / "techpack-headers"

BP_FILE = HERE / "Android.bp"
BP_BEGIN = "// BEGIN This file is auto-generated by cp_headers.py, do not edit"
BP_END = "// END This file is auto-generated by cp_headers.py, do not edit"


def TP(p):
    return f"../techpack/{p}"


# Core headers -> kernel-headers/, roots relative to kernel/include
CORE_ROOTS = [
    "uapi",
    "../arch/arm64/include/uapi",
]

# Headers bionic already ships are not installed again:
BIONIC_KERNEL = AOSP_ROOT / "bionic/libc/kernel"
BIONIC_UAPI = [
    BIONIC_KERNEL / "uapi",
    BIONIC_KERNEL / "android/uapi",
]

# techpack dir -> ([bp module names], [roots])
#              or a list of such groups: each group gets its own dir
#              techpack-headers/<techpack>/<first module> and its own modules
# root: "dir" (all *.h below it) or ("dir", ["a/b.h", ...]) (only those files)
TECHPACKS = {
    "audio":    (["qti_audio_kernel_uapi"], [TP("audio/include/uapi/audio")]),
    # TODO: Validate. The BSP may require a different path or a different module name
    # https://github.com/sonyxperiadev/vendor-qcom-opensource-camera-kernel/blob/1d3f989b7be114fe3a453c3024ee946e57f1eb92/include/uapi/Android.mk#L10
    "camera":   (["camera-uapi"], [TP("camera/include/uapi/camera")]),
    "dataipa": [
        (["qti_ipa_kernel_headers"], [TP("dataipa/drivers/platform/msm/include/uapi")]),
        (["qti_ipa_test_kernel_headers"], [
            (TP("dataipa/drivers/platform/msm/ipa/ipa_test_module"), ["ipa_test_module.h"])
        ]),
    ],
    "display":  (["qti_display_kernel_headers"], [TP("display/include/uapi")]),
    "eva":      (["qti_eva_kernel_headers"], [TP("eva/include/uapi")]),
    "graphics": (["qti_gfx_kernel_uapi"], [TP("graphics/include/uapi")]),
    "mm": (["qti_mm_drivers_kernel_headers"], [TP("mm/sync_fence/include/uapi")]),
    "securemsm": [
        (["smcinvoke_kernel_headers"], [
            (TP("securemsm/include/uapi"), ["linux/smcinvoke.h"]),
            (TP("securemsm/include"), ["linux/smcinvoke_object.h", "linux/smci_object.h",
                                       "linux/IClientEnv.h", "linux/smci_clientenv.h"]),
        ]),
        (["qseecom_kernel_headers"], [
            (TP("securemsm/include/uapi"), ["linux/qseecom.h", "linux/qseecom_api.h"]),
        ]),
        (["securemsm_kernel_uapi_headers"], [TP("securemsm/include/uapi")]),
        (["smmu_proxy_uapi_header"], [TP("securemsm/smmu-proxy/include/uapi")]),
    ],
    "spu":      (["qti_spu_drivers_kernel_headers"], [TP("spu/include/uapi")]),
    "synx":     (["qti_synx_kernel_headers"], [TP("synx/include/uapi")]),
    "video":    (["qti_video_kernel_uapi"], [TP("video/include/uapi")]),
}

MARK = {"new": "+", "updated": "~", "unchanged": "="}

# Set in main()
VERBOSE = False
LOG = None
HEADERS_INSTALL = None
UNIFDEF = None
PREV = {}  # path -> sha1 of the headers from the previous run


def groups_of(value):
    """A techpack is one (modules, roots) group or a list of such groups."""
    return value if isinstance(value, list) else [value]


def group_name(tp, groups, modules):
    """Dir name below techpack-headers/: tp, or tp/<first module> if tp has several groups."""
    return tp if len(groups) == 1 else f"{tp}/{modules[0]}"


def label_of(root):
    """Text shown for a root: "dir" or "dir (N files)"."""
    if isinstance(root, tuple):
        return "%s (%d files)" % (root[0], len(root[1]))
    return root


# Column widths of the output
LABEL_W = max(
    len(label_of(r))
    for r in CORE_ROOTS
    + [r for v in TECHPACKS.values() for _, roots in groups_of(v) for r in roots]
)
NAME_W = max(
    len(n)
    for n in ["core"]
    + [
        group_name(tp, groups_of(v), modules)
        for tp, v in TECHPACKS.items()
        for modules, _ in groups_of(v)
    ]
)


def say(msg=""):
    """Print and write to the log."""
    print(msg)
    LOG.write(msg + "\n")


def clean(d: Path):
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)


def sha1(p: Path):
    return hashlib.sha1(p.read_bytes()).hexdigest()


def snapshot():
    """Hashes of the previous run's headers (taken before the dirs are cleaned)."""
    return {
        p: sha1(p)
        for d in (CORE_DIR, TECHPACKS_DIR)
        if d.is_dir()
        for p in d.rglob("*.h")
    }


def status_of(out: Path):
    old = PREV.get(out)
    if old is None:
        return "new"
    return "unchanged" if old == sha1(out) else "updated"


def removed_in(d: Path):
    """Headers that were in d on the previous run and are gone now."""
    return sorted(p for p in PREV if d in p.parents and not p.exists())


def in_bionic(rel: Path):
    """The bionic dir that already has this header, or None."""
    return next((d for d in BIONIC_UAPI if (d / rel).is_file()), None)


def installed(c: Counter):
    return c["new"] + c["updated"] + c["unchanged"]


def counts(c: Counter):
    return "%3d new, %3d updated, %3d unchanged" % (c["new"], c["updated"], c["unchanged"])


def setup_tools(tmp: Path):
    """Build unifdef and write the patched headers_install.sh into tmp."""
    global HEADERS_INSTALL, UNIFDEF

    UNIFDEF = os.environ.get("UNIFDEF")
    if not UNIFDEF:
        UNIFDEF = str(tmp / "unifdef")
        cc = os.environ.get("CC", "cc")
        subprocess.check_call(
            [cc, "-O2", "-o", UNIFDEF, str(KERNEL / "scripts/unifdef.c")]
        )

    text = (KERNEL / "scripts/headers_install.sh").read_text()
    if "scripts/unifdef" not in text:
        say("warning: 'scripts/unifdef' not found in headers_install.sh, not patched")
    text = text.replace("scripts/unifdef", "${LOC_UNIFDEF:-$(dirname $0)/unifdef}")
    HEADERS_INSTALL = str(tmp / "headers_install.sh")
    Path(HEADERS_INSTALL).write_text(text)


def sanitize(base: Path, rel: Path, out_dir: Path):
    """sh headers_install.sh <in> <out>"""
    env = dict(os.environ, LOC_UNIFDEF=UNIFDEF)
    return subprocess.run(
        ["sh", HEADERS_INSTALL, str(base / rel), str(out_dir / rel)],
        env=env,
        capture_output=True,
        text=True,
    )


def install_root(root, out_dir: Path, skip_bionic=False, files=None):
    """Install headers below root: all *.h, or only `files` (relative to root).
    Returns a Counter (new/updated/unchanged/failed/skipped)."""
    c = Counter()
    base = (SRC / root).resolve()
    label = label_of(root if files is None else (root, files))
    if not base.is_dir():
        say("  %-*s MISSING (skipped)" % (LABEL_W, label))
        return c

    paths = sorted(base.rglob("*.h")) if files is None else [base / f for f in files]

    LOG.write("-- %s\n" % base)
    for f in paths:
        rel = f.relative_to(base)

        if not f.is_file():
            c["failed"] += 1
            LOG.write("FAIL %s (not found)\n" % rel)
            print("error: %s not found in %s" % (rel, base), file=sys.stderr)
            continue

        if skip_bionic and in_bionic(rel):
            c["skipped"] += 1
            LOG.write("SKIP %s (in bionic)\n" % rel)
            if VERBOSE:
                print("    - %s (bionic)" % rel)
            continue

        out = out_dir / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        r = sanitize(base, rel, out_dir)
        if r.returncode != 0:
            c["failed"] += 1
            LOG.write("FAIL %s\n%s%s" % (rel, r.stdout, r.stderr))
            print(
                "error: %s failed (%d):\n%s%s"
                % (rel, r.returncode, r.stdout, r.stderr),
                file=sys.stderr,
            )
            continue

        status = status_of(out)
        c[status] += 1
        LOG.write("OK   %-9s %s\n" % (status, rel))
        if status == "updated" or VERBOSE:
            print("    %s %s %s" % (MARK[status], status, rel))

    note = ", %d skipped (in bionic)" % c["skipped"] if skip_bionic else ""
    empty = "  <-- EMPTY" if sum(c.values()) == 0 else ""
    say(
        "  %-*s %4d installed (%s), %d failed%s%s"
        % (LABEL_W, label, installed(c), counts(c), c["failed"], note, empty)
    )
    return c


def install_roots(roots, out_dir: Path, skip_bionic=False):
    """Install several roots into one dir. A root is "dir" (all headers)
    or ("dir", [files]) (only those files). Returns the summed Counter."""
    total = Counter()
    for root in roots:
        root, files = root if isinstance(root, tuple) else (root, None)
        total += install_root(root, out_dir, skip_bionic, files)
    return total


def install_core():
    """Returns (summary entries, bp modules). The core module always exists."""
    say("== core -> %s/" % CORE_DIR.name)
    if not BIONIC_UAPI[0].is_dir():
        say("warning: %s not found, nothing will be skipped" % BIONIC_UAPI[0])
    clean(CORE_DIR)
    c = install_roots(CORE_ROOTS, CORE_DIR, skip_bionic=True)
    return [("core", CORE_DIR, c)], [("qti_kernel_headers", CORE_DIR.name)]


def install_techpacks():
    """Returns (summary entries, bp modules). A group without headers gets no dir
    and no module."""
    summary, bp_modules = [], []
    shutil.rmtree(TECHPACKS_DIR, ignore_errors=True)
    for tp, value in TECHPACKS.items():
        groups = groups_of(value)
        for modules, roots in groups:
            name = group_name(tp, groups, modules)
            say("== techpack %s" % name)
            out = TECHPACKS_DIR / name
            out.mkdir(parents=True)
            c = install_roots(roots, out)
            if installed(c) == 0:
                shutil.rmtree(out)
                say("  no headers, %s stay dummies" % ", ".join(modules))
            else:
                bp_modules += [(m, f"{TECHPACKS_DIR.name}/{name}") for m in modules]
            summary.append((name, out, c))
    return summary, bp_modules


def update_bp(modules):
    """Replace (or append) the generated block of common-headers/Android.bp.
    modules: [(module name, dir relative to common-headers)]"""
    lines = [BP_BEGIN]
    for name, d in sorted(modules, key=lambda x: f"{x[0]}_{VERSION}"):
        lines.append(f"""
cc_library_headers {{
    name: "{name}_{VERSION}",
    vendor_available: true,
    recovery_available: true,
    export_include_dirs: ["{d}"],
}}""")
    lines.append("\n" + BP_END + "\n")
    block = "\n".join(lines)

    text = BP_FILE.read_text() if BP_FILE.exists() else ""
    b, e = text.find(BP_BEGIN), text.find(BP_END)

    if (b == -1) != (e == -1) or text.count(BP_BEGIN) > 1 or text.count(BP_END) > 1:
        raise RuntimeError("invalid generated block markers in Android.bp")

    if b != -1:
        if e < b:
            raise RuntimeError("invalid generated block order in Android.bp")
        text = text[:b] + block + text[e + len(BP_END) :].lstrip("\n")
    else:
        text = text.rstrip("\n") + ("\n\n" if text.strip() else "") + block

    tmp = BP_FILE.with_name(BP_FILE.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(BP_FILE)


def print_summary(summary):
    say("\n== summary")
    for name, d, c in summary:
        removed = removed_in(d)
        say(
            "  %-*s %5d headers (%s), %d failed, %d removed"
            % (NAME_W, name, installed(c), counts(c), c["failed"], len(removed))
        )
        for p in removed:
            LOG.write("REMOVED %s\n" % p.relative_to(HERE))
            if VERBOSE:
                print("    x removed %s" % p.relative_to(HERE))


def main():
    global VERBOSE, LOG, PREV
    ap = argparse.ArgumentParser(
        description="Install kernel UAPI headers into common-headers"
    )
    ap.add_argument("-v", "--verbose", action="store_true", help="print every header")
    VERBOSE = ap.parse_args().verbose
    PREV = snapshot()
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp, open(LOG_PATH, "w") as LOG:
        setup_tools(Path(tmp))

        summary, bp_modules = install_core()
        tp_summary, tp_modules = install_techpacks()
        summary += tp_summary
        bp_modules += tp_modules

        errors = sum(c["failed"] for _, _, c in summary)
        if errors:
            say("Android.bp not updated because header installation failed")
        else:
            update_bp(bp_modules)

        print_summary(summary)

        if errors:
            say("  Android.bp: not updated")
        else:
            say("  Android.bp: %d modules" % len(bp_modules))
        say("  log: %s" % LOG_PATH)
        say("Done, %d error(s)" % errors)

    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
